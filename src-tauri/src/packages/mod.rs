//! 从 GitHub 发现并安装 Skill / 插件 / 宠物资源包。
//!
//! 设计上刻意分成三步，且第二步必须由人经过：
//!   1. `search` —— 只读，返回候选仓库及其判断信号（星数、更新时间、归档、许可证）
//!   2. `fetch` —— 下载指定仓库快照，解析清单，生成待确认预览（**不安装**）
//!   3. `install` —— 用户确认后，把暂存目录交给既有安装器
//!
//! 为什么不让模型一步装完：插件可以贡献 Skill，而 Skill 正文会进入模型上下文
//! （`activate_skill` 的审批策略是 Never）。也就是说恶意包的实际风险不是执行代码，
//! 而是**带持久性的提示注入**。同时插件签名验证尚未接入可信发布者目录。
//! 因此「装哪个仓库」这个信任决策必须留在用户手里，模型只能搜索与陈述。

