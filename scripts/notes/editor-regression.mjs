import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";

const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [], checks = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto(`${process.env.NOTE_TEST_URL ?? "http://localhost:1422"}/scripts/notes/editor-harness.html`);
  const firstCell = page.getByRole("textbox", { name: "第 1 行，第 1 列", exact: true });
  await firstCell.waitFor();
  await firstCell.focus();
  const beforeComposition = await page.evaluate(() => window.noteFixture.session.snapshot().content);
  await firstCell.evaluate((input) => {
    input.dispatchEvent(new CompositionEvent("compositionstart", { bubbles: true, data: "" }));
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set.call(input, "中文😀");
    input.dispatchEvent(new InputEvent("input", { bubbles: true, data: "中文😀", isComposing: true }));
  });
  assert.equal(await page.evaluate(() => window.noteFixture.session.snapshot().content), beforeComposition);
  assert.equal(await page.evaluate(() => window.noteFixture.session.isComposing), true);
  await firstCell.evaluate((input) => input.dispatchEvent(new CompositionEvent("compositionend", { bubbles: true, data: "中文😀" })));
  await page.waitForFunction(() => window.noteFixture.session.snapshot().content.includes("中文😀"));
  assert.equal(await page.evaluate(() => window.noteFixture.session.isComposing), false);
  checks.push("table composition preserves the source until compositionend");
  await firstCell.fill("left||right");
  await page.waitForFunction(() => window.noteFixture.session.snapshot().content.includes("left\\|\\|right"));
  assert.equal(await page.getByRole("textbox", { name: "表头，第 3 列", exact: true }).count(), 1);
  await firstCell.evaluate((input) => {
    const clipboardData = new DataTransfer(); clipboardData.setData("text/plain", "A\tB\nC\tD");
    input.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData }));
  });
  await page.waitForFunction(() => window.noteFixture.session.snapshot().content.includes("| C | D |"));
  checks.push("table pipes and rectangular TSV preserve columns");
  await page.getByRole("button", { name: "源码", exact: true }).click();
  await page.evaluate(() => window.noteFixture.session.edit({ content: "# Fixture\n\n==重点== <u>下划线</u> $x^2$ and $5 and $10\n\n```python\nprint('old')\n```\n\n[Jump](#fixture)\n\nTail\n" }));
  await page.getByRole("textbox", { name: "Markdown 笔记正文", exact: true }).click();
  await page.keyboard.press("Control+Home");
  await page.getByRole("button", { name: "实时编辑", exact: true }).click();
  await page.locator(".note-inline-math .katex").waitFor();
  assert.equal(await page.locator(".note-inline-math").count(), 1);
  await page.locator(".note-live-highlight").waitFor();
  await page.getByRole("button", { name: "编辑块源码", exact: true }).first().click();
  const block = page.getByRole("textbox", { name: "块 Markdown 源码", exact: true });
  await block.waitFor(); await block.fill("```python\nprint('new')\n```");
  await page.waitForFunction(() => window.noteFixture.session.snapshot().content.includes("print('new')"));
  await block.press("Control+s");
  await page.waitForFunction(() => !window.noteFixture.session.dirty);
  await block.press("Control+z");
  await page.waitForFunction(() => window.noteFixture.session.snapshot().content.includes("print('old')"));
  checks.push("inline syntax and local code editing share save and undo");
  await page.getByRole("button", { name: "阅读", exact: true }).click();
  await page.locator(".note-editor-reading a").first().waitFor();
  const anchor = await page.getByRole("link", { name: "Jump", exact: true }).getAttribute("href");
  assert.ok(anchor.startsWith("#mnemora-heading-"));
  assert.equal(await page.locator(anchor).count(), 1);
  await page.getByRole("button", { name: "查找替换", exact: true }).click();
  assert.equal(await page.getByRole("textbox", { name: "替换文本", exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "替换全部", exact: true }).isDisabled(), true);
  await page.getByRole("textbox", { name: "查找文本", exact: true }).fill("(a+)+$");
  await page.getByLabel("正则", { exact: true }).check();
  await page.getByRole("button", { name: "下一个", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "正则支持" }).waitFor();
  checks.push("reading anchors and immutable bounded search");
  await page.getByRole("button", { name: "源码", exact: true }).click();
  await page.getByRole("button", { name: "关闭查找", exact: true }).click();
  await page.getByLabel("Language", { exact: true }).selectOption("en");
  await page.getByRole("button", { name: "Live", exact: true }).waitFor();
  await page.getByRole("button", { name: "Live", exact: true }).click();
  await page.getByRole("button", { name: "Edit block source", exact: true }).waitFor();
  checks.push("English toolbar and independent block roots");
  assert.deepEqual(errors, []);
  await fs.writeFile(new URL("../../.artifacts/plan16/regression-report.json", import.meta.url), JSON.stringify({ result: "passed", browser: browser.version(), checks }, null, 2));
  console.log(JSON.stringify({ result: "passed", checks }));
} finally { await browser.close(); }
